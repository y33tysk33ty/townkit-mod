package townkit.api.bubble;

/**
 * How an icon feels. It sets the pitch of the "huh" a villager makes when the bubble pops up, as for Towntopia's own
 * icons: low for negative, normal for neutral, high for positive.
 *
 * @since 0.7.0
 */
public enum Valence {
    POSITIVE,
    NEUTRAL,
    NEGATIVE
}
